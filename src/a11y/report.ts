import type { Audit, Violation } from './audit'
import type { Criterion, Standard } from './standards'
import { RGAA_THEMES, RGAA_VERSION } from './rgaa-criteria'
import { judge, unfiled } from './standards'

const MAX_NODES = 5

export interface A11yReport extends Audit {
  standard: Standard
  criteria: Criterion[]
  // The findings no criterion of the standard files, which the draft lists apart.
  unfiled: Violation[]
}

export function reportOf(audit: Audit, standard: Standard): A11yReport {
  return { ...audit, standard, criteria: judge(standard, audit.violations, audit.audited.length > 0 && audit.skipped.length === 0), unfiled: unfiled(standard, audit.violations) }
}

// Whether the audit fails a CI run: any finding, a page the site got wrong, or no page audited at all.
export function failed(report: Pick<A11yReport, 'audited' | 'violations' | 'skipped'>): boolean {
  return report.audited.length === 0 || report.violations.length > 0 || report.skipped.some(page => page.failed)
}

// Each rule with the pages it fails on and the elements, each with the `.kay` line it comes from where kay could map it.
export function formatReport(report: A11yReport): string {
  const lines: string[] = []
  const byRule = new Map<string, Violation[]>()

  for (const violation of report.violations)
    byRule.set(violation.rule, [...byRule.get(violation.rule) ?? [], violation])

  for (const [rule, found] of byRule) {
    const [first] = found

    lines.push(`${rule}${first!.impact === null ? '' : ` (${first!.impact})`}: ${first!.help}`, `  ${first!.helpUrl}`)

    for (const violation of found) {
      lines.push(`  ${violation.route}  ${violation.file}`)

      for (const node of violation.nodes.slice(0, MAX_NODES))
        lines.push(`    ${node.target}${node.source === undefined ? '' : `  ${node.source}`}`)

      if (violation.nodes.length > MAX_NODES)
        lines.push(`    and ${violation.nodes.length - MAX_NODES} more`)
    }

    lines.push('')
  }

  if (report.skipped.length > 0) {
    lines.push('Not audited:')

    for (const page of report.skipped)
      lines.push(`  ${page.path}  ${page.file}: ${page.why}`)

    lines.push('')
  }

  return lines.join('\n')
}

interface Tally {
  verified: number
  failed: number
  review: number
}

export function tally(criteria: Criterion[]): Tally {
  return { verified: criteria.filter(each => each.status === 'verified').length, failed: criteria.filter(each => each.status === 'failed').length, review: criteria.filter(each => each.status === 'review').length }
}

