import { chmod, mkdir } from 'node:fs/promises'
import { join } from 'node:path'
import process from 'node:process'
import { beforeAll, describe, expect, it } from 'bun:test'
import { completionCheck } from '../src/commands/completion'
import { scratchDir } from './scratch'

const cli = join(import.meta.dir, '../src/cli.ts')
const DESCRIPTION = /\t.*$/
const SHELLS = ['bash', 'zsh', 'fish'] as const

let bin: string
let home: string

// A `kay` on the PATH that runs this checkout, so a shell's completion function calls what it was written for.
beforeAll(async () => {
  const root = await scratchDir('completion-')

  bin = join(root, 'bin')
  home = join(root, 'home')
  await mkdir(bin, { recursive: true })
  await mkdir(home, { recursive: true })
  await Bun.write(join(bin, 'kay'), `#!/bin/sh\nexec ${process.execPath} ${cli} "$@"\n`)
  await chmod(join(bin, 'kay'), 0o755)
})

function kay(...args: string[]) {
  const child = Bun.spawnSync([process.execPath, cli, ...args], { cwd: home, env: { PATH: process.env.PATH!, HOME: home } })

  return { code: child.exitCode, out: child.stdout.toString(), err: child.stderr.toString() }
}

// A shell run with the `kay` above on its PATH, no profile read.
function shell(name: string, args: string[]) {
  const child = Bun.spawnSync([name, ...args], { cwd: home, env: { PATH: `${bin}:${process.env.PATH}`, HOME: home } })

  return { code: child.exitCode, out: child.stdout.toString(), err: child.stderr.toString() }
}

describe('kay completion', () => {
  it('prints the glue of each shell, headed by the command that wrote it', () => {
    const marks = { bash: 'complete -F __kaynooo_cli_complete kay', zsh: 'compdef __kaynooo_cli_complete kay', fish: 'complete -c kay -f' }

    for (const name of SHELLS) {
      const { code, out } = kay('completion', name)

      expect(code).toBe(0)
      expect(out.startsWith(`# Generated by \`kay completion ${name}\`\n`)).toBe(true)
      expect(out).toContain(marks[name])
      expect(out).toContain('__complete')
    }
  })

  it('refuses a missing shell and an unknown one', () => {
    expect(kay('completion')).toMatchObject({ code: 2, out: '' })
    expect(kay('completion')).toHaveProperty('err', expect.stringContaining('name a shell: fish, bash, zsh'))
    expect(kay('completion', 'pwsh')).toMatchObject({ code: 2, out: '' })
    expect(kay('completion', 'bash', 'zsh').code).toBe(2)
  })

  it.skipIf(Bun.which('bash') === null)('has bash complete a command and an option of kay', async () => {
    await Bun.write(join(home, 'kay.bash'), kay('completion', 'bash').out)

    const complete = (words: string[]) => shell('bash', ['--norc', '--noprofile', '-c', `source kay.bash; COMP_WORDS=(${words.map(word => `'${word}'`).join(' ')}); COMP_CWORD=${words.length - 1}; __kaynooo_cli_complete; printf '%s\\n' "\${COMPREPLY[@]}"`])

    expect(complete(['kay', 'chec']).out.split('\n')).toContain('check')
    expect(complete(['kay', 'editor', 'ins']).out.split('\n')).toContain('install')
    expect(complete(['kay', 'doctor', '--for']).out.split('\n')).toContain('--format')
    expect(shell('bash', ['--norc', '--noprofile', '-c', 'source kay.bash; complete -p kay']).out).toContain('-F __kaynooo_cli_complete kay')
  })

  it.skipIf(Bun.which('fish') === null)('has fish complete a command and an option of kay', async () => {
    await Bun.write(join(home, 'kay.fish'), kay('completion', 'fish').out)

    const complete = (line: string) => shell('fish', ['--no-config', '-c', `source kay.fish; complete -C '${line}'`]).out.split('\n').map(row => row.replace(DESCRIPTION, ''))

    expect(complete('kay chec')).toContain('check')
    expect(complete('kay editor ins')).toContain('install')
    expect(complete('kay doctor --for')).toContain('--format')
  })

  it.skipIf(Bun.which('zsh') === null)('is a script zsh parses', async () => {
    await Bun.write(join(home, 'kay.zsh'), kay('completion', 'zsh').out)

    expect(shell('zsh', ['-f', '-n', 'kay.zsh']).code).toBe(0)
  })
})

describe('the completion check of kay doctor', () => {
  it('names no shell kay has no script for', () => {
    expect(completionCheck('', home, '')).toMatchObject({ name: 'complete', ok: true, message: 'no shell named in SHELL' })
    expect(completionCheck('/usr/bin/nu', home, '')).toMatchObject({ ok: true, message: expect.stringContaining('nu has no kay completion') })
  })

  it('warns with the line to run while a shell has none', () => {
    expect(completionCheck('/bin/fish', home, '')).toMatchObject({ ok: true, warning: true, fix: expect.stringContaining('kay completion fish >') })
    expect(completionCheck('/bin/bash', home, '')).toMatchObject({ warning: true, fix: expect.stringContaining('source <(kay completion bash)') })
    expect(completionCheck('/bin/zsh', home, '')).toMatchObject({ warning: true, fix: expect.stringContaining('source <(kay completion zsh)') })
  })

  it('is satisfied by the file or the rc line that sets it up', async () => {
    const set = await scratchDir('completion-home-')

    await Bun.write(join(set, '.bashrc'), '# kay\nsource <(kay completion bash)\n')
    await Bun.write(join(set, '.zshrc'), 'alias k=kay\n')
    await Bun.write(join(set, '.config/fish/completions/kay.fish'), '')

    expect(completionCheck('/bin/bash', set, '')).toMatchObject({ ok: true, message: `bash completion set up in ${join(set, '.bashrc')}` })
    expect(completionCheck('/bin/zsh', set, '')).toMatchObject({ warning: true })
    expect(completionCheck('/bin/fish', set, '')).toMatchObject({ message: expect.stringContaining('fish completion set up') })
    expect(completionCheck('/bin/fish', set, '').warning).toBeUndefined()
  })
})
