import type { CompletionShell } from '@kaynooo/cli-kit'
import type { Command } from './command'
import type { Check } from './doctor'
import { existsSync, readFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { basename, join } from 'node:path'
import process from 'node:process'
import { COMPLETION_SHELLS, completionScript } from '@kaynooo/cli-kit'

// What a shell's rc file holds once the completion is set up, however it was written there.
const INSTALLED = /kay (?:completion|--completions)/

// Prints the glue that has a shell ask `kay __complete` for the word being typed, to be sourced from the shell's rc file or saved where fish reads its completions.
export const completion: Command = {
  usage: 'completion <bash|zsh|fish>',
  options: {},
  positionals: 1,
  run: ({ positionals: [shell] }, refuse) => {
    if (shell === undefined)
      return refuse(`name a shell: ${COMPLETION_SHELLS.join(', ')}`)

    if (!COMPLETION_SHELLS.includes(shell as CompletionShell))
      return refuse(`${shell} is none of ${COMPLETION_SHELLS.join(', ')}`)

    process.stdout.write(completionScript(shell as CompletionShell, ['kay'], `# Generated by \`kay completion ${shell}\``))

    return 0
  },
}

// Where each shell is told about the completion: fish reads `kay.fish` from its completions folder, bash and zsh source it from an rc file.
function installs(shell: CompletionShell, home: string, xdg: string): { files: string[], fix: string } {
  const config = xdg === '' ? join(home, '.config') : xdg

  if (shell === 'fish')
    return { files: [join(config, 'fish', 'completions', 'kay.fish')], fix: 'run `kay completion fish > ~/.config/fish/completions/kay.fish`' }

  if (shell === 'zsh')
    return { files: [join(home, '.zshrc')], fix: 'add `source <(kay completion zsh)` to ~/.zshrc, after compinit' }

  return { files: [join(home, '.bashrc'), join(home, '.bash_profile')], fix: 'add `source <(kay completion bash)` to ~/.bashrc' }
}

// The shell completion of `kay`, which a shell given in SHELL either has set up or is told how to; a warning only, as no app needs it.
export function completionCheck(shell = process.env.SHELL ?? '', home = homedir(), xdg = process.env.XDG_CONFIG_HOME ?? ''): Check {
  const name = basename(shell)

  if (!COMPLETION_SHELLS.includes(name as CompletionShell))
    return { name: 'complete', ok: true, message: shell === '' ? 'no shell named in SHELL' : `${name} has no kay completion (${COMPLETION_SHELLS.join(', ')} have)` }

  const { files, fix } = installs(name as CompletionShell, home, xdg)
  const found = files.find(file => existsSync(file) && (name === 'fish' || INSTALLED.test(readFileSync(file, 'utf8'))))

  return found === undefined
    ? { name: 'complete', ok: true, warning: true, message: `${name} completes no kay command or option yet`, fix }
    : { name: 'complete', ok: true, message: `${name} completion set up in ${found}` }
}
