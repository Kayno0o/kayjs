const escaped = (text: string): string => text.replaceAll('|', '\\|')

// The accessibility statement drafted from the report: the pages audited and left out, every criterion of the standard marked verified, failed or to review, and the failures with where they are.
export function declaration(report: A11yReport, date = new Date().toISOString().slice(0, 10)): string {
  const words = WORDS[report.standard]
  const counts = tally(report.criteria)
  const out: string[] = [`# ${words.title}`, '', `> ${words.note(date, report.audited.length, counts, report.criteria.length)}`, '', `## ${words.state}`, '', words.stateText, '', `## ${words.audited}`, '']

  out.push(...report.audited.length === 0 ? [words.none] : report.audited.map(page => `- \`${page.path}\` (${page.file})`), '', `## ${words.skipped}`, '')
  out.push(...report.skipped.length === 0 ? [words.none] : report.skipped.map(page => `- \`${page.path}\` (${page.file}): ${page.why}`), '', `## ${words.results}`, '')

  if (report.standard === 'rgaa') {
    for (const [index, theme] of RGAA_THEMES.entries()) {
      out.push(`### ${index + 1}. ${theme}`, '', words.columns)

      for (const criterion of report.criteria.filter(each => each.id.startsWith(`${index + 1}.`)))
        out.push(row(criterion, words))

      out.push('')
    }
  }
  else {
    out.push(words.columns)

    for (const criterion of report.criteria)
      out.push(row(criterion, words))

    out.push('')
  }

  const failing = report.criteria.filter(each => each.status === 'failed')

  out.push(`## ${words.findings}`, '')

  if (failing.length === 0)
    out.push(words.none, '')

  for (const criterion of failing) {
    out.push(`### ${criterion.id} ${criterion.title}`, '')

    for (const violation of report.violations.filter(each => criterion.failures.some(({ rule, route }) => rule === each.rule && route === each.route)))
      out.push(...describe(violation))

    out.push('')
  }

  if (report.unfiled.length > 0) {
    out.push(`## ${words.elsewhere}`, '', words.unfiledText, '')

    for (const violation of report.unfiled)
      out.push(...describe(violation))

    out.push('')
  }

  out.push(`## ${words.contact}`, '', words.contactText, '')

  return out.join('\n')
}

function row(criterion: Criterion, words: Words): string {
  const detail = criterion.failures.map(({ rule, route }) => `\`${rule}\` on \`${route}\``).join(', ')

  return `| ${criterion.id} ${escaped(criterion.title)} | ${words.statuses[criterion.status]} | ${escaped(detail)} |`
}

function describe(violation: Violation): string[] {
  return [`- \`${violation.rule}\` on \`${violation.route}\`: ${violation.help}`, ...violation.nodes.slice(0, MAX_NODES).map(node => `  - \`${node.target}\`${node.source === undefined ? '' : ` (${node.source})`}`)]
}
