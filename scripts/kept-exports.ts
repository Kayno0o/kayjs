import type { Comment, Statement } from '@babel/types'
import { readFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import process from 'node:process'
import { parse } from '@babel/parser'

// Writes src/server/kept-exports.ts, the class a kept page gives each export of kay's public entries, from the `// kept: <class>` line among the comments right above the export's declaration in its own module: `bun scripts/kept-exports.ts`.
// `tests/kept-exports.test.ts` fails for an export with no such line and for a map this would write differently.
const ROOT = resolve(import.meta.dir, '..')

export const KEPT_EXPORTS = 'src/server/kept-exports.ts'
const KEPT = /^\s*kept: (\w+)/
const TYPE_DECLARATIONS = new Set(['TSInterfaceDeclaration', 'TSTypeAliasDeclaration', 'TSModuleDeclaration'])

// Each public entry by the map it fills, with the classes a page may take its exports as.
const ENTRIES = [
  { map: 'KAY_EXPORTS', entry: 'src/runtime/index.ts', classes: ['free', 'request', 'local'], about: '`kay`' },
  { map: 'CONTENT_EXPORTS', entry: 'src/content/index.ts', classes: ['free', 'request', 'folder'], about: '`kay/content`' },
  { map: 'IMAGE_EXPORTS', entry: 'src/runtime/image.public.ts', classes: ['free'], about: '`kay/image`' },
  { map: 'I18N_EXPORTS', entry: 'src/runtime/i18n.server.ts', classes: ['free', 'request'], about: '`kay/i18n`' },
] as const

const HEADER = `// Generated by \`bun scripts/kept-exports.ts\` from the \`// kept:\` line above each export of kay's public entries, where the reason for its class is: edit those, then run it again.
// Whether a page taking the export stays the same for every visitor and every moment: \`free\` reads no request, cookie, environment or clock; \`request\` does, or opens a route, a socket or a call that does.
// \`local\` is free only where every call says \`storage: 'local'\`, and \`folder\` only where every call starts with a folder written as a string.
`

export interface KeptExports {
  // The file's text as the script writes it.
  text: string
  // Each export with no class, or with one its entry does not take, naming where it is declared.
  problems: string[]
}

// The modules a search went through, and the declaration it ended on when that one has no class.
interface Trail {
  seen: Set<string>
  at?: string | undefined
}

const modules = new Map<string, Statement[]>()

function bodyOf(file: string): Statement[] {
  let body = modules.get(file)

  if (body === undefined)
    modules.set(file, body = parse(readFileSync(file, 'utf8'), { sourceType: 'module', plugins: ['typescript'] }).program.body)

  return body
}

function resolved(specifier: string, from: string): string {
  return Bun.resolveSync(specifier, dirname(from))
}

function classOf(comments: readonly Comment[] | null | undefined): string | undefined {
  for (const comment of comments ?? []) {
    const found = comment.type === 'CommentLine' ? KEPT.exec(comment.value) : null

    if (found !== null)
      return found[1]
  }

  return undefined
}

function exportedName(node: { type: 'Identifier', name: string } | { type: 'StringLiteral', value: string }): string {
  return node.type === 'Identifier' ? node.name : node.value
}

function declares(declaration: Statement, name: string): boolean {
  if (declaration.type === 'VariableDeclaration')
    return declaration.declarations.some(declarator => declarator.id.type === 'Identifier' && declarator.id.name === name)

  return 'id' in declaration && declaration.id != null && declaration.id.type === 'Identifier' && declaration.id.name === name
}

// The class of the binding `name` declares in `file`, following an import or a re-export to the module that declares it; `null` for a binding that is a type.
// An overloaded function takes its class from any of its signatures.
function bindingClass(file: string, name: string, trail: Trail): string | undefined | null {
  const key = `${file}#${name}`

  if (trail.seen.has(key))
    return undefined

  trail.seen.add(key)

  const body = bodyOf(file)

  for (const statement of body) {
    const declaration = statement.type === 'ExportNamedDeclaration' ? statement.declaration : statement

    if (declaration == null || !declares(declaration, name))
      continue

    if (TYPE_DECLARATIONS.has(declaration.type))
      return null

    trail.at ??= `${relative(ROOT, file)}:${statement.loc?.start.line}`

    const found = classOf(statement.leadingComments)

    if (found !== undefined)
      return found
  }

  if (trail.at !== undefined)
    return undefined

  for (const statement of body) {
    if (statement.type !== 'ImportDeclaration' || statement.importKind === 'type')
      continue

    for (const specifier of statement.specifiers) {
      if (specifier.local.name === name && specifier.type === 'ImportSpecifier')
        return bindingClass(resolved(statement.source.value, file), exportedName(specifier.imported), trail)
    }
  }

  return exportClass(file, name, trail)
}

// The class of the export `name` of `file`, wherever the module takes it from.
function exportClass(file: string, name: string, trail: Trail): string | undefined | null {
  const body = bodyOf(file)

  for (const statement of body) {
    if (statement.type !== 'ExportNamedDeclaration' || statement.declaration != null)
      continue

    for (const specifier of statement.specifiers) {
      if (specifier.type !== 'ExportSpecifier' || exportedName(specifier.exported) !== name)
        continue

      if (statement.exportKind === 'type' || specifier.exportKind === 'type')
        return null

      return bindingClass(statement.source == null ? file : resolved(statement.source.value, file), specifier.local.name, trail)
    }
  }

  for (const statement of body) {
    if (statement.type === 'ExportNamedDeclaration' && statement.declaration != null && declares(statement.declaration, name))
      return bindingClass(file, name, trail)

    if (statement.type === 'ExportAllDeclaration' && statement.exportKind !== 'type') {
      const target = resolved(statement.source.value, file)

      if (valueNames(target).has(name))
        return exportClass(target, name, trail)
    }
  }

  return undefined
}

// The value names a module exports, its types left out, `export *` followed.
function valueNames(file: string, seen = new Set<string>()): Set<string> {
  const names = new Set<string>()

  if (seen.has(file))
    return names

  seen.add(file)

  for (const statement of bodyOf(file)) {
    if (statement.type === 'ExportAllDeclaration' && statement.exportKind !== 'type') {
      for (const name of valueNames(resolved(statement.source.value, file), seen))
        names.add(name)
    }

    if (statement.type !== 'ExportNamedDeclaration' || statement.exportKind === 'type')
      continue

    const { declaration } = statement

    if (declaration?.type === 'VariableDeclaration') {
      for (const declarator of declaration.declarations) {
        if (declarator.id.type === 'Identifier')
          names.add(declarator.id.name)
      }
    }
    else if (declaration != null && !TYPE_DECLARATIONS.has(declaration.type) && 'id' in declaration && declaration.id?.type === 'Identifier') {
      names.add(declaration.id.name)
    }

    for (const specifier of statement.specifiers) {
      if (specifier.type === 'ExportSpecifier' && specifier.exportKind !== 'type')
        names.add(exportedName(specifier.exported))
    }
  }

  return names
}

// The text of src/server/kept-exports.ts, and what keeps an export from its class.
export function keptExports(): KeptExports {
  modules.clear()

  const problems: string[] = []
  let text = HEADER

  for (const { map, entry, classes, about } of ENTRIES) {
    const file = join(ROOT, entry)
    const lines: string[] = []

    for (const name of [...valueNames(file)].sort()) {
      const trail: Trail = { seen: new Set() }
      const kept = exportClass(file, name, trail)

      if (kept === null)
        continue

      if (kept === undefined || !(classes as readonly string[]).includes(kept)) {
        problems.push(`${about} \`${name}\` (${trail.at ?? entry}) ${kept === undefined ? 'has no `// kept:` line' : `is \`kept: ${kept}\`, where ${about} takes ${classes.join(', ')}`}`)

        continue
      }

      lines.push(`  ${name}: '${kept}',`)
    }

    text += `\n// The exports of ${about}.\nexport const ${map}: Record<string, ${classes.map(kept => `'${kept}'`).join(' | ')}> = {\n${lines.join('\n')}\n}\n`
  }

  return { text, problems }
}

if (import.meta.main) {
  const { text, problems } = keptExports()

  if (problems.length > 0) {
    console.error(`kept-exports: each export needs a \`// kept: <class>\` line among the comments above its declaration:\n${problems.map(problem => `  ${problem}`).join('\n')}`)
    process.exit(1)
  }

  await Bun.write(join(ROOT, KEPT_EXPORTS), text)
  console.log(`wrote ${relative(process.cwd(), join(ROOT, KEPT_EXPORTS))}`)
}
